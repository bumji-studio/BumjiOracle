    analyzeTenGodsCounts: function (counts, isWeak) {
      const results = {
        dominantGods: [],
        excessiveGods: [],
        specialPatterns: []
      };

      // Sort by count
      const sorted = Object.entries(counts).sort((a, b) => b[1] - a[1]);
      if (sorted.length > 0 && sorted[0][1] > 0) {
        const maxVal = sorted[0][1];
        results.dominantGods = sorted.filter(item => item[1] >= maxVal && maxVal >= 2).map(item => ({
          god: item[0],
          count: item[1],
          info: TEN_GODS_INFO[item[0]]
        }));
      }

      // Check excessive
      for (const [god, cnt] of Object.entries(counts)) {
        const info = TEN_GODS_INFO[god];
        if (info && info.excessiveCondition && cnt >= info.excessiveCondition.threshold) {
          results.excessiveGods.push({
            god,
            count: cnt,
            analysis: info.excessiveCondition
          });
        }
      }

      // Check special patterns
      for (const pat of SPECIAL_COMBINATIONS) {
        if (pat.condition(counts, isWeak)) {
          results.specialPatterns.push(pat);
        }
      }

      return results;
    },

